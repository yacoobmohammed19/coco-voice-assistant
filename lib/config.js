function findClaudeExe() {
  const candidates = [
    path.join(os.homedir(), '.local', 'bin', 'claude.exe'),
    path.join(process.env.APPDATA || '', 'npm', 'node_modules', '@anthropic-ai', 'claude-code', 'bin', 'claude.exe'),
  ];
  return candidates.find((p) => fs.existsSync(p)) || 'claude';
}

function load() {
  let cfg = {};
  try {
    cfg = JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8').replace(/^﻿/, ''));
  } catch (e) {
    if (e.code !== 'ENOENT') console.error(`[config] could not read ${CONFIG_FILE}: ${e.message}`);
  }
  const merged = { ...DEFAULTS, ...cfg };
  if (!merged.claudeExe) merged.claudeExe = findClaudeExe();
  if (process.env.ANTHROPIC_API_KEY && !merged.anthropicApiKey) merged.anthropicApiKey = process.env.ANTHROPIC_API_KEY;
  return merged;
}

function save(cfg) {
  fs.mkdirSync(DATA, { recursive: true });
  const out = {};
  for (const k of Object.keys(DEFAULTS)) if (cfg[k] !== undefined && k !== 'claudeExe') out[k] = cfg[k];
  fs.writeFileSync(CONFIG_FILE, JSON.stringify(out, null, 2));
}

module.exports = { load, save, ROOT, DATA, CONFIG_FILE };
